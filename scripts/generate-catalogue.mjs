function loadExistingImages() {
  try {
    const current = JSON.parse(fs.readFileSync(OUT_PATH, "utf8"));
    return new Map((current.items || []).map((item) => [item.id, item.image]));
  } catch {
    return new Map();
  }
}

function imageForItem(id, categoryId, previousImages) {
  const previous = previousImages.get(id);
  if (
    previous &&
    previous.startsWith("/images/") &&
    !previous.includes("..") &&
    fs.existsSync(path.join(__dirname, "..", "public", previous.replace(/^\//, "").replaceAll("/", path.sep)))
  ) {
    return previous;
  }
  const photoPath = `/images/menu/${id}.webp`;
  if (fs.existsSync(path.join(__dirname, "..", "public", photoPath.slice(1)))) return photoPath;
  return `/images/fallbacks/${categoryId}.webp`;
}

function buildMenu() {
  const categories = [];
  const items = [];
  const usedIds = new Set();
  const previousImages = loadExistingImages();

  CATEGORY_DATA.forEach((cat, catIndex) => {
    categories.push({
      id: cat.id,
      name: cat.name,
      description: cat.description,
      isActive: true,
      sortOrder: catIndex + 1,
    });

    cat.items.forEach((row, itemIndex) => {
      const [name, nameHi, description, listedPrice, tags, spiceLevel, variantPairs] = row;
      const id = kebab(name);
      if (!id) {
        throw new Error(`Empty id for dish "${name}"`);
      }
      if (usedIds.has(id)) {
        throw new Error(`Duplicate id "${id}" from name "${name}"`);
      }
      usedIds.add(id);

      let variants = [];
      if (Array.isArray(variantPairs) && variantPairs.length) {
        variants = variantPairs.map(([vName, vPrice]) => ({
          id: `${id}-${kebab(vName)}`,
          name: vName,
          price: vPrice,
        }));
      }

      const price =
        variants.length > 0 ? Math.min(...variants.map((v) => v.price)) : listedPrice;

      const image = imageForItem(id, cat.id, previousImages);

      items.push({
        id,
        categoryId: cat.id,
        name,
        nameHi: nameHi ?? "",
        description,
        price,
        image,
        tags: tags ?? [],
        spiceLevel: spiceLevel ?? "",
        isActive: ACTIVE_NAMES.has(name),
        isFeatured: FEATURED_NAMES.has(name),
        sortOrder: itemIndex + 1,
        variants,
      });
    });
  });

  return {
    schemaVersion: 1,
    revision: "initial",
    generatedAt: new Date().toISOString(),
    notice:
      "Catalogue prices and availability are initial suggestions and require owner review before launch.",
    restaurant: {
      name: "The Maati Cafe & Restaurant",
      currency: "INR",
      description: "Cafe favourites and Indian classics. Scan, browse, and place your order with your server.",
      address: "",
      phone: "",
      openingHours: "",
      footerText: "Ask your server to place your order. Prices are listed in Indian Rupees.",
      wifi: { enabled: false, name: "", password: "" },
    },
    categories,
    items,
  };
}

function validate(menu) {
  const itemCount = menu.items.length;
  const uniqueIdCount = new Set(menu.items.map((i) => i.id)).size;
  const activeCount = menu.items.filter((i) => i.isActive).length;
  const featured = menu.items.filter((i) => i.isFeatured);
  const categoryCount = menu.categories.length;
  const emptyCategories = menu.categories
    .filter((c) => !menu.items.some((i) => i.categoryId === c.id))
    .map((c) => c.id);

  const nameBuckets = new Map();
  for (const item of menu.items) {
    const key = normalizeName(item.name);
    if (!nameBuckets.has(key)) nameBuckets.set(key, []);
    nameBuckets.get(key).push(item.name);
  }
  const duplicateNormalizedNames = [...nameBuckets.entries()]
    .filter(([, names]) => names.length > 1)
    .map(([key, names]) => `${key} -> ${names.join(" | ")}`);

  const missingActive = [...ACTIVE_NAMES].filter(
    (name) => !menu.items.some((i) => i.name === name),
  );
  const missingFeatured = [...FEATURED_NAMES].filter(
    (name) => !menu.items.some((i) => i.name === name),
  );
  const inactiveFeatured = featured.filter((i) => !i.isActive).map((i) => i.name);
  const nonVegHints = menu.items.filter((i) =>
    /\b(egg|omelette|chicken|mutton|fish|prawn|beer|wine|rum|vodka|whisky|alcohol)\b/i.test(
      `${i.name} ${i.description}`,
    ),
  );

  const warnings = [];
  if (missingActive.length) warnings.push(`Missing ACTIVE names: ${missingActive.join(", ")}`);
  if (missingFeatured.length)
    warnings.push(`Missing FEATURED names: ${missingFeatured.join(", ")}`);
  if (inactiveFeatured.length)
    warnings.push(`Featured but inactive: ${inactiveFeatured.join(", ")}`);
  if (nonVegHints.length)
    warnings.push(
      `Possible non-veg/alcohol wording: ${nonVegHints.map((i) => i.name).join(", ")}`,
    );

  return {
    itemCount,
    uniqueIdCount,
    activeCount,
    featuredCount: featured.length,
    featuredNames: featured.map((i) => i.name),
    categoryCount,
    emptyCategories,
    duplicateNormalizedNames,
    warnings,
  };
}

function main() {
  const menu = buildMenu();
  const report = validate(menu);

  fs.mkdirSync(path.dirname(OUT_PATH), { recursive: true });
  fs.writeFileSync(OUT_PATH, `${JSON.stringify(menu, null, 2)}\n`, "utf8");

  console.log(`Catalogue written to ${OUT_PATH}`);
  console.log(`item count: ${report.itemCount}`);
  console.log(`unique id count: ${report.uniqueIdCount}`);
  console.log(`active count: ${report.activeCount}`);
  console.log(`featured count: ${report.featuredCount}`);
  console.log(`featured names: ${report.featuredNames.join(", ")}`);
  console.log(`category count: ${report.categoryCount}`);
  console.log(
    `empty categories: ${report.emptyCategories.length ? report.emptyCategories.join(", ") : "none"}`,
  );
  console.log(
    `duplicate normalized names: ${
      report.duplicateNormalizedNames.length
        ? report.duplicateNormalizedNames.join("; ")
        : "none"
    }`,
  );
  if (report.warnings.length) {
    for (const warning of report.warnings) console.log(`warning: ${warning}`);
  }
  if (report.itemCount < 560) {
    throw new Error(`Need at least 560 items, got ${report.itemCount}`);
  }
  if (report.uniqueIdCount !== report.itemCount) {
    throw new Error("Duplicate ids detected");
  }
  if (report.emptyCategories.length) {
    throw new Error(`Empty categories: ${report.emptyCategories.join(", ")}`);
  }
}

main();

